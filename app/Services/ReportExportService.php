<?php

namespace App\Services;

use Illuminate\Support\Collection;
use Symfony\Component\HttpFoundation\StreamedResponse;

class ReportExportService
{
    /**
     * Export FHSIS Morbidity Report as CSV.
     */
    public function exportMorbidityCsv(
        Collection $rows,
        int $totalCases,
        string $reportDate,
        int $month,
        int $year,
        string $sexLabel,
        string $zoneLabel,
        string $ageGroupLabel
    ): StreamedResponse {
        $filename = "Morbidity_Report_Sta_Ana_{$month}_{$year}.csv";

        $headers = [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ];

        return response()->streamDownload(function () use ($rows, $totalCases, $reportDate, $sexLabel, $zoneLabel, $ageGroupLabel) {
            $handle = fopen('php://output', 'w');

            // Header section
            fputcsv($handle, ['Barangay Health Center Information System']);
            fputcsv($handle, ['Sta. Ana Barangay Health Center']);
            fputcsv($handle, ['FHSIS-style report (M2-style layout)']);
            fputcsv($handle, ['Generated by BHCIS - supports, does not replace, official FHSIS forms']);
            fputcsv($handle, []);
            fputcsv($handle, ['Monthly Morbidity Disease Report']);
            fputcsv($handle, ['Leading Causes of Morbidity']);
            fputcsv($handle, ["Report Period: {$reportDate}"]);
            fputcsv($handle, ["Selected filters: Sex: {$sexLabel} | Zone: {$zoneLabel} | Age group: {$ageGroupLabel}"]);
            fputcsv($handle, []);

            // Data header
            fputcsv($handle, ['ICD Code', 'Diagnosis / Cause', 'Cases']);

            // Data rows
            foreach ($rows as $row) {
                fputcsv($handle, [
                    $row->diagnosis_code,
                    $row->diagnosis_name,
                    (int) $row->case_count,
                ]);
            }

            // Total row
            fputcsv($handle, ['', 'Total Cases', (int) $totalCases]);

            fclose($handle);
        }, $filename, $headers);
    }

    /**
     * Export Merged MCH/EPI/FP Report as CSV.
     */
    public function exportMchEpiFpCsv(
        array $report,
        string $zoneLabel,
        string $programLabel
    ): StreamedResponse {
        $from = $report['filters']['from'] ?? 'unknown';
        $to = $report['filters']['to'] ?? 'unknown';
        $filename = "MCH_EPI_FP_Report_Sta_Ana_{$from}_{$to}.csv";

        $headers = [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ];

        return response()->streamDownload(function () use ($report, $zoneLabel, $programLabel) {
            $handle = fopen('php://output', 'w');

            // Header section
            fputcsv($handle, ['Barangay Health Center Information System']);
            fputcsv($handle, ['Sta. Ana Barangay Health Center']);
            fputcsv($handle, ['FHSIS-style report (M1-style layout)']);
            fputcsv($handle, ['Generated by BHCIS - supports, does not replace, official FHSIS forms']);
            fputcsv($handle, []);
            fputcsv($handle, ['Monthly Maternal, EPI & Family Planning Report']);
            fputcsv($handle, ["Report Period: {$report['reportDate']} | Zone: {$zoneLabel} | Program: {$programLabel}"]);
            fputcsv($handle, []);

            // Maternal summaries
            if (! empty($report['summaries']['maternal'])) {
                $m = $report['summaries']['maternal'];
                fputcsv($handle, ['Maternal Care']);
                fputcsv($handle, ['Indicator', 'Count']);
                fputcsv($handle, ['New prenatal clients registered', (int) $m['newPrenatalClients']]);
                fputcsv($handle, ['Prenatal visits conducted', (int) $m['prenatalVisits']]);
                fputcsv($handle, ['Pregnant women with 4+ prenatal visits', (int) $m['prenatalFourPlus']]);
                fputcsv($handle, ['TT doses', (int) $m['ttDoses']]);
                fputcsv($handle, ['Iron supplementation', (int) $m['ironSupplemented']]);
                fputcsv($handle, ['Syphilis screening - reactive', (int) $m['syphilisPositive']]);
                fputcsv($handle, ['Deliveries', (int) $m['totalDeliveries']]);
                fputcsv($handle, ['Postnatal within 24 hours', (int) $m['postpartum24h']]);
                fputcsv($handle, ['Postnatal within 7 days', (int) $m['postpartum7d']]);
                fputcsv($handle, ['Postnatal within 14 days', (int) $m['postpartum14d']]);
                fputcsv($handle, ['Postnatal within 28 days', (int) $m['postpartum28d']]);
                fputcsv($handle, []);

                // Deliveries by place
                fputcsv($handle, ['Deliveries by Place']);
                fputcsv($handle, ['Place', 'Count']);
                foreach ($m['deliveriesByPlace'] as $row) {
                    fputcsv($handle, [MchEpiFpReportService::placeLabel($row->key), (int) $row->total]);
                }
                fputcsv($handle, []);

                // Deliveries by attendant
                fputcsv($handle, ['Deliveries by Attendant']);
                fputcsv($handle, ['Attendant', 'Count']);
                foreach ($m['deliveriesByAttendant'] as $row) {
                    fputcsv($handle, [MchEpiFpReportService::attendantLabel((string) $row->key), (int) $row->total]);
                }
                fputcsv($handle, []);

                // Deliveries by outcome
                fputcsv($handle, ['Deliveries by Outcome']);
                fputcsv($handle, ['Outcome', 'Count']);
                foreach ($m['deliveriesByOutcome'] as $row) {
                    fputcsv($handle, [MchEpiFpReportService::outcomeLabel($row->key), (int) $row->total]);
                }
                fputcsv($handle, []);
            }

            // EPI summaries
            if (! empty($report['summaries']['epi'])) {
                $e = $report['summaries']['epi'];
                fputcsv($handle, ['EPI Immunization']);
                fputcsv($handle, ['Indicator', 'Count']);
                fputcsv($handle, ['Child doses', (int) $e['childDoses']]);
                fputcsv($handle, ['Adult doses', (int) $e['adultDoses']]);
                fputcsv($handle, ['Total doses given', (int) $e['totalDoses']]);
                fputcsv($handle, ['Fully Immunized Children (FIC)', (int) $e['fic']]);
                fputcsv($handle, ['Child Protected at Birth (CPAB)', (int) $e['cpab']]);
                fputcsv($handle, []);

                // Doses by sex
                if (! empty($e['dosesBySex'])) {
                    fputcsv($handle, ['Doses by Sex']);
                    fputcsv($handle, ['Sex', 'Doses']);
                    fputcsv($handle, ['Male', (int) $e['dosesBySex']['Male']]);
                    fputcsv($handle, ['Female', (int) $e['dosesBySex']['Female']]);
                    fputcsv($handle, ['Total', (int) $e['dosesBySex']['Total']]);
                    fputcsv($handle, []);
                }

                // Doses by vaccine
                fputcsv($handle, ['Doses by Vaccine']);
                fputcsv($handle, ['Vaccine', 'Dose', 'Doses Administered']);
                foreach ($e['dosesByVaccine'] as $row) {
                    fputcsv($handle, [$row->vaccine_name, $row->dose_number, (int) $row->doses]);
                }
                fputcsv($handle, []);
            }

            // FP summaries
            if (! empty($report['summaries']['fp'])) {
                $f = $report['summaries']['fp'];
                fputcsv($handle, ['Family Planning']);
                fputcsv($handle, ['Indicator', 'Count']);
                fputcsv($handle, ['New acceptors', (int) $f['totalNew']]);
                fputcsv($handle, ['Continuing users', (int) $f['totalContinuing']]);
                fputcsv($handle, ['Drop outs', (int) $f['totalDropOuts']]);
                fputcsv($handle, ['Others', (int) $f['totalOthers']]);
                fputcsv($handle, ['Visits conducted', (int) $f['totalVisits']]);
                fputcsv($handle, ['Total clients', (int) $f['totalClients']]);
                fputcsv($handle, []);

                // Clients by sex
                if (! empty($f['clientsBySex'])) {
                    fputcsv($handle, ['Clients by Sex']);
                    fputcsv($handle, ['Sex', 'Clients']);
                    fputcsv($handle, ['Male', (int) $f['clientsBySex']['Male']]);
                    fputcsv($handle, ['Female', (int) $f['clientsBySex']['Female']]);
                    fputcsv($handle, ['Total', (int) $f['clientsBySex']['Total']]);
                    fputcsv($handle, []);
                }

                // By method
                fputcsv($handle, ['FP by Method']);
                fputcsv($handle, ['Method', 'New Acceptors', 'Continuing Users', 'Drop Outs', 'Others', 'Visits', 'Total']);
                foreach ($f['rows'] as $row) {
                    fputcsv($handle, [
                        $row->method,
                        (int) $row->new_acceptors,
                        (int) $row->continuing_users,
                        (int) $row->drop_outs,
                        (int) $row->others,
                        (int) $row->visits,
                        (int) $row->total,
                    ]);
                }
                fputcsv($handle, []);
            }

            // Natality summaries
            if (! empty($report['summaries']['natality'])) {
                $n = $report['summaries']['natality'];
                fputcsv($handle, ['Natality (M1 Section I)']);
                fputcsv($handle, ['Indicator', 'Value']);
                fputcsv($handle, ['Live Births', (int) $n['liveBirths']]);
                fputcsv($handle, ['CBR (per 1,000 population)', (float) $n['cbr']]);
                fputcsv($handle, []);
                fputcsv($handle, ['Live Births by Mother Age Band']);
                fputcsv($handle, ['Age Band', 'Count']);
                fputcsv($handle, ['10-14', (int) $n['byMotherAge']['10-14']]);
                fputcsv($handle, ['15-19', (int) $n['byMotherAge']['15-19']]);
                fputcsv($handle, ['20-49', (int) $n['byMotherAge']['20-49']]);
                fputcsv($handle, []);
            }

            fclose($handle);
        }, $filename, $headers);
    }
}
